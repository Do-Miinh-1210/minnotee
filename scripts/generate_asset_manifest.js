#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ALLOWED_EXTENSIONS = new Set(['.html', '.js', '.css']);

function walkWhiteboardAssets(rootDir, currentDir, results) {
  const entries = fs.readdirSync(currentDir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(currentDir, entry.name);
    if (entry.isDirectory()) {
      walkWhiteboardAssets(rootDir, fullPath, results);
    } else if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (ALLOWED_EXTENSIONS.has(ext)) {
        const relPath = path.relative(rootDir, fullPath).split(path.sep).join('/');
        results.push({ relPath, fullPath });
      }
    }
  }
}

function escapeCSharpString(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function main() {
  const repoRoot = path.resolve(__dirname, '..');
  const whiteboardDir = path.join(repoRoot, 'Resources', 'Whiteboard');
  const outputPath = path.join(repoRoot, 'Services', 'AssetManifest.Generated.cs');

  if (!fs.existsSync(whiteboardDir) || !fs.statSync(whiteboardDir).isDirectory()) {
    console.error(`[generate_asset_manifest] Whiteboard directory not found: ${whiteboardDir}`);
    process.exit(1);
  }

  const files = [];
  walkWhiteboardAssets(whiteboardDir, whiteboardDir, files);

  if (files.length === 0) {
    console.error(`[generate_asset_manifest] No .html/.js/.css files found in: ${whiteboardDir}`);
    process.exit(1);
  }

  // Deterministic invariant code-point sort (locale-independent)
  files.sort((a, b) => (a.relPath < b.relPath ? -1 : a.relPath > b.relPath ? 1 : 0));

  const entries = files.map(({ relPath, fullPath }) => {
    const content = fs.readFileSync(fullPath);
    const sha256 = crypto.createHash('sha256').update(content).digest('hex').toLowerCase();
    return { relPath, sha256 };
  });

  const generatedUtc = new Date().toISOString();
  const lines = [
    '// <auto-generated />',
    '// Generated by scripts/generate_asset_manifest.js — do not edit manually.',
    '#nullable enable',
    '',
    'using System;',
    'using System.Collections.Generic;',
    '',
    'namespace MinNote.Services',
    '{',
    '    internal static partial class AssetManifest',
    '    {',
    `        public const string GeneratedUtc = "${escapeCSharpString(generatedUtc)}";`,
    `        public const int FileCount = ${entries.length};`,
    '',
    '        public static readonly IReadOnlyDictionary<string, string> ExpectedSha256 =',
    '            new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)',
    '            {',
  ];

  for (const { relPath, sha256 } of entries) {
    lines.push(`                ["${escapeCSharpString(relPath)}"] = "${sha256}",`);
  }

  lines.push(
    '            };',
    '    }',
    '}',
    ''
  );

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, lines.join('\n'), { encoding: 'utf8' });

  console.log(
    `[generate_asset_manifest] Generated Services/AssetManifest.Generated.cs (${entries.length} files, UTC ${generatedUtc}).`
  );
}

main();
